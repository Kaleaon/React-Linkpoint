/** Look up a canonical LSL event signature by event name. */
export function getLSLEventSignature(name: string): LSLEventSignature | undefined {
  return Object.prototype.hasOwnProperty.call(LSL_EVENT_SIGNATURES, name)
    ? LSL_EVENT_SIGNATURES[name]
    : undefined;
}

/** Look up a canonical LSL built-in function signature by `ll*` name (or `ll.<Name>` SLua call). */
export function getLSLFunctionSignature(name: string): LSLFunctionSignature | undefined {
  const normalized = name.startsWith('ll.') ? `ll${name.slice(3)}` : name;
  return Object.prototype.hasOwnProperty.call(LSL_BUILTIN_FUNCTIONS, normalized)
    ? LSL_BUILTIN_FUNCTIONS[normalized]
    : undefined;
}

/** Look up a canonical LSL constant value by identifier. */
export function getLSLConstantValue(name: string): number | string | readonly number[] | undefined {
  return Object.prototype.hasOwnProperty.call(LSL_CONSTANTS, name)
    ? LSL_CONSTANTS[name]
    : undefined;
}

/**
 * Decode an integer bitmask against a canonical flag map (e.g. `LSL_CONTROL_FLAGS`,
 * `LSL_AGENT_INFO_FLAGS`, `LSL_PERMISSION_FLAGS`, `LSL_CHANGED_FLAGS`), returning matching
 * single-bit flag names in ascending bit order.
 */
export function decodeLSLBitmask<T extends Record<string, number>>(
  mask: number,
  flagTable: T,
): Array<Extract<keyof T, string>> {
  const normalizedMask = mask >>> 0;
  const matched: Array<{ key: Extract<keyof T, string>; bit: number }> = [];
  for (const [key, rawBit] of Object.entries(flagTable)) {
    const bit = rawBit >>> 0;
    // Match single-bit flags (powers of two) that are set in mask
    if (bit !== 0 && (bit & (bit - 1)) === 0 && (normalizedMask & bit) === bit) {
      matched.push({ key: key as Extract<keyof T, string>, bit });
    }
  }
  matched.sort((a, b) => a.bit - b.bit || a.key.localeCompare(b.key));
  return matched.map((item) => item.key);
}
