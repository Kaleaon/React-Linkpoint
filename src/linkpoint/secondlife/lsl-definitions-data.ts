export type LSLValueType = 'integer' | 'float' | 'string' | 'key' | 'vector' | 'rotation' | 'list';

export type LSLReturnType = LSLValueType | 'void';

export interface LSLParameterSignature {
  readonly name: string;
  readonly type: LSLValueType;
}

export interface LSLEventSignature {
  readonly name: string;
  readonly eventId: number;
  readonly parameters: readonly LSLParameterSignature[];
  readonly categories: readonly string[];
  readonly description: string;
}

export interface LSLFunctionSignature {
  readonly name: string;
  readonly returnType: LSLReturnType;
  readonly parameters: readonly LSLParameterSignature[];
  readonly functionId: number | null;
  readonly energy: number;
  readonly sleep: number;
  readonly pure: boolean;
  readonly categories: readonly string[];
  readonly sluaNote?: string;
}

export interface SLuaKeywordDefinition {
  readonly keyword: string;
  readonly description: string;
}

export interface SLuaBuiltinTypeDefinition {
  readonly type: string;
  readonly description: string;
}

export interface SLuaGlobalModuleDefinition {
  readonly name: string;
  readonly origin: 'luau-stdlib' | 'slua-runtime';
  readonly members: readonly string[];
  readonly description: string;
}

